const languageStorageKey = 'freschi-language';
const defaultLanguage = 'it';

function getSavedLanguage() {
  const saved = localStorage.getItem(languageStorageKey);
  return saved && translations[saved] ? saved : defaultLanguage;
}

function applyLanguage(language) {
  const selectedLanguage = translations[language] ? language : defaultLanguage;

  document.documentElement.lang = selectedLanguage;
  document.documentElement.setAttribute('data-lang', selectedLanguage);

  const title = document.querySelector('title');
  if (title && translations[selectedLanguage][title.dataset.i18n]) {
    title.textContent = translations[selectedLanguage][title.dataset.i18n];
  }

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (translations[selectedLanguage][key]) {
      element.textContent = translations[selectedLanguage][key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (translations[selectedLanguage][key]) {
      element.placeholder = translations[selectedLanguage][key];
    }
  });

  document.querySelectorAll('[data-i18n-attr]').forEach((element) => {
    const rawValue = element.dataset.i18nAttr || '';
    const [attributeName, key] = rawValue.split(':');
    if (attributeName && key && translations[selectedLanguage][key]) {
      element.setAttribute(attributeName, translations[selectedLanguage][key]);
    }
  });

  document.querySelectorAll('[data-bs-toggle="popover"]').forEach((element) => {
    const key = element.dataset.i18nPop;
    if (key && translations[selectedLanguage][key]) {
      element.setAttribute('data-bs-content', translations[selectedLanguage][key]);
    }
  });

  document.querySelectorAll('[data-lang-toggle]').forEach((button) => {
    const isActive = button.dataset.langToggle === selectedLanguage;
    button.classList.toggle('active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });

  localStorage.setItem(languageStorageKey, selectedLanguage);
}

document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('[data-lang-toggle]').forEach((button) => {
    button.addEventListener('click', () => {
      applyLanguage(button.dataset.langToggle);
    });
  });

  applyLanguage(getSavedLanguage());
});
